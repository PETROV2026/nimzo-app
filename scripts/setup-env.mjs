#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const force = process.argv.includes('--force');

const refFile = join(root, 'supabase/.temp/project-ref');
if (!existsSync(refFile)) {
  console.error('Supabase project is not linked. Run:');
  console.error('  pnpm supabase login');
  console.error('  pnpm supabase link --project-ref <project-ref>');
  process.exit(1);
}

const ref = readFileSync(refFile, 'utf8').trim();
const url = `https://${ref}.supabase.co`;

let anonKey;
try {
  const output = execFileSync(
    'pnpm',
    ['exec', 'supabase', 'projects', 'api-keys', '--project-ref', ref, '-o', 'json'],
    { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] },
  );
  const keys = JSON.parse(output);
  anonKey = keys.find((key) => key.name === 'anon' || key.type === 'publishable')?.api_key;
} catch {}
if (!anonKey) {
  console.error('Could not read the anon key. Check that you are logged in: pnpm supabase login');
  process.exit(1);
}

function existingValue(relativePath, name) {
  const path = join(root, relativePath);
  if (!existsSync(path)) return '';
  const line = readFileSync(path, 'utf8')
    .split('\n')
    .find((entry) => entry.startsWith(`${name}=`));
  return line ? line.slice(name.length + 1) : '';
}

const files = {
  'apps/admin/.env': [
    '# Generated by `pnpm env:setup`. Supabase dashboard → Project Settings → API.',
    `VITE_SUPABASE_URL=${url}`,
    `VITE_SUPABASE_ANON_KEY=${anonKey}`,
    '# Cloudflare dashboard → Turnstile → widget → Site Key.',
    `VITE_TURNSTILE_SITE_KEY=${existingValue('apps/admin/.env', 'VITE_TURNSTILE_SITE_KEY')}`,
  ],
  'apps/mobile/.env': [
    '# Generated by `pnpm env:setup`. Supabase dashboard → Project Settings → API.',
    `EXPO_PUBLIC_SUPABASE_URL=${url}`,
    `EXPO_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  ],
};

for (const [relativePath, lines] of Object.entries(files)) {
  const path = join(root, relativePath);
  if (existsSync(path) && !force) {
    console.log(`skip     ${relativePath} (already exists, use --force to overwrite)`);
    continue;
  }
  writeFileSync(path, `${lines.join('\n')}\n`);
  console.log(`written  ${relativePath}`);
}

console.log(`\nProject: ${ref}`);
